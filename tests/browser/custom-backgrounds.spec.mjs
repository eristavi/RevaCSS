import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('custom colorful stops persist across modes/pages and export without editor scripts',async({page})=>{
  await page.goto('/demos/backgrounds/');
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  await page.locator('#demo-background').selectOption('colorful');
  await expect(page.locator('#custom-background-editor')).toBeVisible();
  const before=await page.locator('[data-background="colorful"]').first().evaluate(el=>getComputedStyle(el).backgroundImage);
  await page.locator('#background-colour-0').fill('#123456');
  await page.locator('#background-colour-0').dispatchEvent('change');
  expect(await page.locator('[data-background="colorful"]').first().evaluate(el=>getComputedStyle(el).backgroundImage)).not.toBe(before);
  await page.locator('#demo-background').selectOption('colorful-animated');
  await expect(page.locator('#background-colour-0')).toHaveValue('#123456');
  await page.goto('/demos/blog/');
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  await expect(page.locator('#background-colour-0')).toHaveValue('#123456');
  const download=page.waitForEvent('download');
  await page.locator('.demo-customizer a[download]').click();
  const html=await readFile(await (await download).path(),'utf8');
  expect(html).toContain('--re-background-color-1: #123456');
  expect(html).toContain('reva.backgrounds.css');
  expect(html).toContain('data-background="colorful-animated"');
  expect(html).not.toMatch(/<script\b/);
  await page.locator('#reset-custom-backgrounds').click();
  await expect(page.locator('#background-colour-0')).not.toHaveValue('#123456');
  await expect(page.locator('#demo-background')).toHaveValue('colorful-animated');
  await page.locator('#demo-background').selectOption('default');
  await expect(page.locator('#custom-background-editor')).toBeHidden();
});
