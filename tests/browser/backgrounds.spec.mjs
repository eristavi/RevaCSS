import {test,expect} from '@playwright/test';
test.use({javaScriptEnabled:false});
for(const scoped of [false,true])test(`colorful backgrounds retain native content and preference fallbacks (${scoped?'scoped':'global'})`,async({page,request})=>{
  const names=scoped?['reva.scoped.css','reva.backgrounds.scoped.css']:['reva.css','reva.backgrounds.css'];
  const css=await Promise.all(names.map(async name=>{const r=await request.get('/reva/'+name);expect(r.ok()).toBe(true);return r.text();}));
  await page.emulateMedia({reducedMotion:'no-preference',forcedColors:'none',contrast:'no-preference'});
  await page.setViewportSize({width:320,height:800});
  await page.setContent(`<!doctype html><html lang="en" ${scoped?'':'data-background="colorful-animated"'}><head><style>${css.join('\n')}</style></head><body><main ${scoped?'class="reva" data-background="colorful-animated"':''} id="root"><h1>Native content</h1><section id="static" data-background="colorful"><h2>Static</h2></section><section id="moving" data-background="colorful-animated"><h2>Moving</h2><a href="#end">Continue</a></section><section id="reset" data-background="default"><h2>Default</h2></section><section data-motion="none"><div id="still" data-background="colorful-animated">No motion</div><div data-motion="expressive"><div id="fast" data-background="colorful-animated">Local expressive</div></div></section><p id="end">Destination</p></main><div id="outside" data-background="colorful">Outside</div></body></html>`);
  const moving=page.locator('#moving'),image=()=>moving.evaluate(el=>getComputedStyle(el).backgroundImage);
  await expect(moving).toHaveCSS('animation-duration','12s');
  await expect(page.locator('#static')).toHaveCSS('background-image',await image());
  await expect(page.locator('#static')).toHaveCSS('animation-name','none');
  await expect(page.locator('#static')).toHaveCSS('background-size','100% 100%');
  await expect(page.locator('#reset')).toHaveCSS('background-image','none');
  await expect(page.locator('#still')).toHaveCSS('animation-name','none');
  await expect(page.locator('#fast')).toHaveCSS('animation-duration','6s');
  const first=await image();
  await page.locator('#root').evaluate(el=>{el.setAttribute('data-theme','dark');el.setAttribute('data-accent','orange');});
  expect(await image()).toBe(first);
  if(scoped)await expect(page.locator('#outside')).toHaveCSS('background-image','none');
  else await expect(page.locator('body')).toHaveCSS('background-image',first);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(moving).toHaveCSS('animation-name','none');
  await expect(moving).toHaveCSS('background-size','100% 100%');
  await page.emulateMedia({reducedMotion:'no-preference',contrast:'more'});
  await expect(moving).toHaveCSS('background-image','none');
  await page.emulateMedia({contrast:'no-preference',forcedColors:'active'});
  await expect(moving).toHaveCSS('background-image','none');
  await page.emulateMedia({forcedColors:'none',media:'print'});
  await expect(moving).toHaveCSS('background-image','none');
});
